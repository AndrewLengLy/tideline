// Captures the default map at 1440px and 375px with panels hidden, shrinks each to a tiny PNG,
// and writes lib/poster.ts. The page paints these before MapLibre loads, so the map is never blank.
// Run against a production build: npx tsx scripts/make-poster.ts http://localhost:3120
import { writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";
import { PNG } from "pngjs";

const BASE = process.argv[2] ?? "http://localhost:3120";

function shrink(buf: Buffer, outW: number, outH: number): string {
  const src = PNG.sync.read(buf);
  const out = new PNG({ width: outW, height: outH });
  for (let y = 0; y < outH; y++) {
    for (let x = 0; x < outW; x++) {
      const x0 = Math.floor((x * src.width) / outW);
      const x1 = Math.floor(((x + 1) * src.width) / outW);
      const y0 = Math.floor((y * src.height) / outH);
      const y1 = Math.floor(((y + 1) * src.height) / outH);
      let r = 0;
      let g = 0;
      let b = 0;
      let n = 0;
      for (let j = y0; j < y1; j++) {
        for (let i = x0; i < x1; i++) {
          const o = (j * src.width + i) * 4;
          r += src.data[o];
          g += src.data[o + 1];
          b += src.data[o + 2];
          n++;
        }
      }
      const o = (y * outW + x) * 4;
      out.data[o] = r / n;
      out.data[o + 1] = g / n;
      out.data[o + 2] = b / n;
      out.data[o + 3] = 255;
    }
  }
  return PNG.sync.write(out, { colorType: 2, deflateLevel: 9 }).toString("base64");
}

async function capture(width: number, height: number, mobile: boolean): Promise<Buffer> {
  const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
  const ctx = await browser.newContext({ viewport: { width, height }, isMobile: mobile, hasTouch: mobile });
  const page = await ctx.newPage();
  await page.goto(BASE, { waitUntil: "domcontentloaded" });
  await page.waitForTimeout(28_000);
  await page.addStyleTag({ content: "header,aside,footer,[data-testid=bottom-panel],[data-testid=mobile-scrubber],[data-testid=bottom-sheet],[data-testid=water-slider],.panel,.callout,.maplibregl-control-container{visibility:hidden!important}" });
  await page.waitForTimeout(400);
  const shot = await page.screenshot({ type: "png" });
  await browser.close();
  return shot;
}

async function main() {
  const desktop = shrink(await capture(1440, 900, false), 24, 15);
  const phone = shrink(await capture(375, 812, true), 12, 26);
  const body = `// Generated by scripts/make-poster.ts. Tiny blurred stand-ins for the default map view, painted before MapLibre loads.
export const POSTER_DESKTOP = 'url("data:image/png;base64,${desktop}")';
export const POSTER_PHONE = 'url("data:image/png;base64,${phone}")';
`;
  writeFileSync("lib/poster.ts", body);
  console.log(`Wrote lib/poster.ts (${body.length} bytes)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
